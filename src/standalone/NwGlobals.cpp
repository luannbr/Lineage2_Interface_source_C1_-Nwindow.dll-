// 0x1011c4c0..0x1011e4c8 .bss; include/nwindow/NCGDevice.h
// GWrapText -> GWrapLine -> GWrapLen -> GWrapPos: the stock code overflows each one into the
// next, so they stay one object in the stock order; the names are references to its
// members. Zero in the stock image.
struct NWrapChain
{
    NWrapBuffer GWrapText;   // +0x0000 (stock 0x1011c4c0)
    NWrapBuffer GWrapLine;   // +0x1000 (stock 0x1011d4c0)
    INT GWrapLen;   // +0x2000 (stock 0x1011e4c0)
    INT GWrapPos;   // +0x2004 (stock 0x1011e4c4)
};
NW_ASSERT_OFFSET(NWrapChain, GWrapLine, 0x1000);
NW_ASSERT_OFFSET(NWrapChain, GWrapLen, 0x2000);
NW_ASSERT_OFFSET(NWrapChain, GWrapPos, 0x2004);
NW_ASSERT_SIZE(NWrapChain, 0x2008);
static NWrapChain GWrapChain;
NWrapBuffer& GWrapText = GWrapChain.GWrapText;
NWrapBuffer& GWrapLine = GWrapChain.GWrapLine;
INT& GWrapLen = GWrapChain.GWrapLen;
INT& GWrapPos = GWrapChain.GWrapPos;

